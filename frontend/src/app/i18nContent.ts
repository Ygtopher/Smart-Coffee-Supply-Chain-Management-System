const wordMaps: Record<Exclude<SupportedLanguage, 'en'>, PhraseMap> = {
  rw: rwWords,
  fr: frWords,
};

const skipPattern = /^([0-9.,:%+\-/()\s]+|[A-Z0-9-]{2,}|[\w.+-]+@[\w.-]+\.\w+)$/;

function normalizeText(value: string) {
  return value.replace(/\s+/g, ' ').trim().replace(/\u2014/g, '-');
}

function matchCase(source: string, translated: string) {
  if (source.toUpperCase() === source) return translated.toUpperCase();
  if (/^[A-Z][a-z]+$/.test(source)) return translated.charAt(0).toUpperCase() + translated.slice(1);
  return translated;
}

function translateByWords(text: string, lang: Exclude<SupportedLanguage, 'en'>) {
  const wordMap = wordMaps[lang];
  let changed = false;
  const translated = text.replace(/[A-Za-z][A-Za-z'-]*/g, (word) => {
    const key = word.toLowerCase().replace(/'s$/, '');
    const found = wordMap[key];
    if (!found) return word;
    changed = true;
    return matchCase(word, found);
  });
  return changed ? translated : text;
}

export function translateContent(text: string, language: string) {
  const lang = language.split('-')[0] as SupportedLanguage;
  if (lang === 'en' || !['rw', 'fr'].includes(lang)) return text;

  const leading = text.match(/^\s*/)?.[0] ?? '';
  const trailing = text.match(/\s*$/)?.[0] ?? '';
  const normalized = normalizeText(text);
  if (!normalized || skipPattern.test(normalized)) return text;

  const phrase = dictionaries[lang][normalized];
  if (phrase) return `${leading}${phrase}${trailing}`;

  const wordTranslated = translateByWords(normalized, lang);
  return `${leading}${wordTranslated}${trailing}`;
}
