export const updateExportOrderStatus = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const orderId = String(req.params.orderId || '');
    const { status, pricePerKg, quoteNotes, batchId, allocations } = req.body;
    if (!status) {
      res.status(400).json({ message: 'Status is required.' });
      return;
    }

    const existing = await prisma.exportOrder.findUnique({ where: { orderId } });
    if (!existing) {
      res.status(404).json({ message: 'Export order not found.' });
      return;
    }
    if (batchId) {
      const batch = await prisma.coffeeBatch.findUnique({ where: { batchId: String(batchId) } });
      if (!batch) {
        res.status(404).json({ message: 'Selected sample batch was not found.' });
        return;
      }
    }

    const nextPrice = pricePerKg !== undefined ? Number(pricePerKg) : Number(existing.pricePerKg);
    const nextTotal = Number(existing.weight) * nextPrice;
    let allocationDetails: any[] = [];
    let finalStatus = status;
    let finalBatchId = batchId ? String(batchId) : existing.batchId;

    if (Array.isArray(allocations)) {
      await ensureExportOrderAllocationStorage();
      const selectedIds = allocations.map((row: any) => String(row.batchId || '')).filter(Boolean);
      if (selectedIds.length === 0) {
        res.status(400).json({ message: 'At least one batch allocation is required.' });
        return;
      }
      const selectedBatches = await prisma.coffeeBatch.findMany({
        where: { batchId: { in: selectedIds }, status: { in: ['export_ready', 'shipment_authorized'] }, qualityAssessments: { some: {} } },
        include: { qualityAssessments: { orderBy: { createdAt: 'desc' }, take: 1 } },
      });
      if (selectedBatches.length !== selectedIds.length) {
        res.status(400).json({ message: 'Only quality-certified export-ready batches can be allocated.' });
        return;
      }
      const reservedRows = selectedIds.length
        ? await prisma.$queryRawUnsafe<Array<{ batch_id: string; reserved_kg: any; order_refs: string | null }>>(
            `SELECT eoba.batch_id,
                    COALESCE(SUM(eoba.allocated_weight_kg), 0) AS reserved_kg,
                    STRING_AGG(COALESCE(eo.reference_code, eo.order_id), ', ') AS order_refs
             FROM export_order_batch_allocations eoba
             JOIN export_orders eo ON eo.order_id = eoba.order_id
             WHERE eoba.order_id <> '${orderId.replace(/'/g, "''")}'
               AND eoba.batch_id IN (${selectedIds.map(id => `'${id.replace(/'/g, "''")}'`).join(',')})
               AND LOWER(eo.status) NOT IN ('rejected', 'delivered', 'cancelled', 'canceled')
             GROUP BY eoba.batch_id`
          )
        : [];
      const reservedByBatch = new Map(reservedRows.map(row => [row.batch_id, Number(row.reserved_kg || 0)]));
      const batchById = new Map(selectedBatches.map(batch => [batch.batchId, batch]));
      let remaining = Number(existing.weight || 0);
      allocationDetails = selectedIds.map(batchIdValue => {
        const batch = batchById.get(batchIdValue);
        if (!batch) return null;
        const requested = Number((allocations.find((row: any) => String(row.batchId) === batchIdValue) || {}).allocatedWeightKg || 0);
        const totalWeightKg = Number(batch.weightCherry || 0);
        const reservedWeightKg = reservedByBatch.get(batchIdValue) || 0;
        const availableWeightKg = Math.max(0, totalWeightKg - reservedWeightKg);
        const allocatedWeightKg = Math.min(
          requested > 0 ? requested : availableWeightKg,
          availableWeightKg,
          Math.max(0, remaining)
        );
        remaining -= allocatedWeightKg;
        return {
          batch,
          batchId: batch.batchId,
          qrCode: batch.qrCode,
          allocatedWeightKg,
          availableWeightKg,
          reservedWeightKg,
          totalWeightKg,
          matchScore: Number((allocations.find((row: any) => String(row.batchId) === batchIdValue) || {}).matchScore || 0),
        };
      }).filter((row: any) => row && Number(row.allocatedWeightKg || 0) > 0);

      if (allocationDetails.length === 0) {
        res.status(400).json({ message: 'Selected batches have no available unreserved quantity.' });
        return;
      }
      const allocatedTotal = allocationDetails.reduce((sum: number, row: any) => sum + Number(row.allocatedWeightKg || 0), 0);
      const fullyCovered = Number(existing.weight || 0) > 0 && allocatedTotal >= Number(existing.weight || 0);
      finalStatus = fullyCovered
        ? (['Ready for Shipment', 'Logistics Authorized'].includes(String(status)) ? 'Ready for Shipment' : 'Matched / Ready for Quote')
        : 'Partially Matched';
      finalBatchId = allocationDetails[0]?.batchId || finalBatchId;
    }

    const order = await prisma.$transaction(async (tx) => {
      if (Array.isArray(allocations)) {
        await tx.$executeRawUnsafe(`DELETE FROM export_order_batch_allocations WHERE order_id = $1`, orderId);
        for (const row of allocationDetails) {
          const match = buildBatchMatch(existing, {
            ...row.batch,
            totalWeightKg: row.totalWeightKg,
            reservedWeightKg: row.reservedWeightKg,
            availableWeightKg: row.availableWeightKg,
          });
          await tx.$executeRawUnsafe(
            `INSERT INTO export_order_batch_allocations
               (allocation_id, order_id, batch_id, allocated_weight_kg, match_score, match_type, created_by)
             VALUES ($1, $2, $3, $4, $5, $6, $7)
             ON CONFLICT (order_id, batch_id) DO UPDATE SET
               allocated_weight_kg = EXCLUDED.allocated_weight_kg,
               match_score = EXCLUDED.match_score,
               match_type = EXCLUDED.match_type,
               created_by = EXCLUDED.created_by,
               created_at = NOW()`,
            `ALC-${Date.now()}-${randomBytes(4).toString('hex')}`,
            orderId,
            row.batchId,
            row.allocatedWeightKg,
            row.matchScore || match.matchScore,
            match.matchType,
            req.user?.userId || null
          );
          await tx.coffeeBatch.update({
            where: { batchId: row.batchId },
            data: { status: 'shipment_authorized' },
          });
        }
      }
      return tx.exportOrder.update({
        where: { orderId },
        data: {
          status: finalStatus,
          ...(pricePerKg !== undefined ? { pricePerKg: nextPrice, totalValue: nextTotal } : {}),
          ...(quoteNotes !== undefined ? { quoteNotes } : {}),
          ...(finalBatchId ? { batchId: String(finalBatchId) } : {}),
        },
        include: { messages: { orderBy: { createdAt: 'asc' } } },
      });
    });

    if (quoteNotes) {
      await prisma.customerOrderMessage.create({
        data: {
          orderId,
          senderType: 'EXPORTER',
          senderName: 'IMPEXCOR Export Team',
          message: quoteNotes,
        },
      });
    }

    const isSample = (existing.qualitySpecs as any)?.requestType === 'SAMPLE' || String(existing.referenceCode || '').startsWith('SMP-');
    if (isSample && status === 'Sample Approved') {
      await ensureSamplePreparationStorage();
      const sampleQuantity = Number((existing.qualitySpecs as any)?.sampleQuantityGrams || Number(existing.weight) * 1000 || 0);
      await prisma.$executeRawUnsafe(
        `INSERT INTO sample_preparations (order_id, batch_id, sample_quantity_g, status, created_by)
         VALUES ($1, $2, $3, 'Awaiting QC Verification', $4)
         ON CONFLICT (order_id) DO UPDATE SET
           batch_id = EXCLUDED.batch_id,
           sample_quantity_g = EXCLUDED.sample_quantity_g,
           status = CASE
             WHEN sample_preparations.status IN ('Dispatched', 'Delivered') THEN sample_preparations.status
             ELSE 'Awaiting QC Verification'
           END,
           updated_at = NOW()`,
        orderId,
        batchId || existing.batchId || null,
        Number.isFinite(sampleQuantity) ? Math.round(sampleQuantity) : null,
        req.user?.userId || null
      );
      const qcUsers = await prisma.user.findMany({
        where: { role: { roleName: 'QUALITY_CONTROLLER' }, status: 'active' },
        select: { userId: true }
      });
      await Promise.all(qcUsers.map(user => createNotification(
        user.userId,
        'Sample Requires QC Verification',
        `Sample request ${order.referenceCode || order.orderId.slice(0, 8)} was approved by Exporter. Verify and release the sample for dispatch.`,
        'info'
      )));
    }

    await prisma.auditLog.create({
      data: {
        userId: req.user?.userId,
        action: 'EXPORT_ORDER_STATUS_UPDATED',
        entityType: 'ExportOrder',
        entityId: orderId,
        details: {
          previousStatus: existing.status,
          status: finalStatus,
          pricePerKg: nextPrice,
          quoteNotes: quoteNotes || null,
          batchId: finalBatchId || existing.batchId || null,
          allocations: allocationDetails.map(row => ({
            batchId: row.batchId,
            qrCode: row.qrCode,
            allocatedWeightKg: row.allocatedWeightKg,
            availableWeightKg: row.availableWeightKg,
          })),
        },
        ipAddress: req.ip,
      },
    });

    res.status(200).json({ success: true, data: order });
  } catch (error) {
    console.error('Error updating export order:', error);
    res.status(500).json({ message: 'Server error updating export order' });
  }
};

