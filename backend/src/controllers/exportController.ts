const parseAuthorizedBatchNotes = (notes?: string | null): Array<{ qrCode: string; allocatedWeightKg: number }> => {
  if (!notes) return [];
  const matches = Array.from(String(notes).matchAll(/(QR-[A-Z0-9-]+)\s*:\s*([\d,.]+)\s*kg/gi));
  return matches
    .map(match => ({
      qrCode: match[1],
      allocatedWeightKg: Number(String(match[2]).replace(/,/g, '')),
    }))
    .filter(row => row.qrCode && Number.isFinite(row.allocatedWeightKg) && row.allocatedWeightKg > 0);
};

const backfillAuthorizedOrderAllocations = async (orders: any[]) => {
  for (const order of orders) {
    const existingRows = await prisma.$queryRawUnsafe<Array<{ count: any }>>(
      `SELECT COUNT(*)::int AS count FROM export_order_batch_allocations WHERE order_id = '${String(order.orderId).replace(/'/g, "''")}'`
    );
    if (Number(existingRows[0]?.count || 0) > 0) continue;

    const parsed = parseAuthorizedBatchNotes(order.quoteNotes);
    const batches = parsed.length
      ? await prisma.coffeeBatch.findMany({ where: { qrCode: { in: parsed.map(row => row.qrCode) } } })
      : order.batchId
        ? await prisma.coffeeBatch.findMany({ where: { batchId: String(order.batchId) } })
        : [];

    for (const batch of batches) {
      const parsedRow = parsed.find(row => row.qrCode === batch.qrCode);
      const allocatedWeight = parsedRow?.allocatedWeightKg || Math.min(Number(order.weight || 0), Number(batch.weightCherry || 0));
      if (!Number.isFinite(allocatedWeight) || allocatedWeight <= 0) continue;
      await prisma.$executeRawUnsafe(
        `INSERT INTO export_order_batch_allocations
           (allocation_id, order_id, batch_id, allocated_weight_kg, match_score, match_type, created_by)
         VALUES ($1, $2, $3, $4, $5, $6, $7)
         ON CONFLICT (order_id, batch_id) DO UPDATE SET
           allocated_weight_kg = EXCLUDED.allocated_weight_kg,
           match_score = EXCLUDED.match_score,
           match_type = EXCLUDED.match_type,
           created_at = NOW()`,
        `ALC-${Date.now()}-${randomBytes(4).toString('hex')}`,
        order.orderId,
        batch.batchId,
        allocatedWeight,
        100,
        'Authorized',
        order.createdBy || null
      );
      if (batch.status === 'export_ready') {
        await prisma.coffeeBatch.update({ where: { batchId: batch.batchId }, data: { status: 'shipment_authorized' } });
      }
    }
  }
};

