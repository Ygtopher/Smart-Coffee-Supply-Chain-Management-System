const withTrackingData = async (shipments: any[]) => {
  await ensureVesselTrackingStorage();
  await ensureRoadTraceabilityStorage();
  const metadata = await prisma.$queryRaw<Array<any>>`
    SELECT shipment_id, mmsi, vessel_id, container_type, seal_no, loaded_weight_kg, loading_date,
      departure_date, estimated_arrival_date, shipping_line, incoterm, destination_market
    FROM shipping_records
  `;
  const latestPositions = await prisma.$queryRaw<Array<any>>`
    SELECT DISTINCT ON (shipment_id) *
    FROM vessel_tracking_positions
    ORDER BY shipment_id, position_time DESC
  `;
  const roadTransports = await prisma.$queryRaw<Array<any>>`
    SELECT * FROM road_transport_records
  `;
  const roadCheckpoints = await prisma.$queryRaw<Array<any>>`
    SELECT * FROM road_transit_checkpoints ORDER BY recorded_at ASC
  `;
  const shipmentIds = shipments.map(shipment => String(shipment.shipmentId || '')).filter(Boolean);
  const orderRows = shipmentIds.length
    ? await prisma.$queryRawUnsafe<Array<any>>(
        `SELECT order_id, reference_code, buyer, company_name, customer_email, customer_phone, weight, grade, country, shipment_id
         FROM export_orders
         WHERE shipment_id IN (${shipmentIds.map(id => `'${id.replace(/'/g, "''")}'`).join(',')})`
      )
    : [];
  const metadataByShipment = new Map(metadata.map(row => [row.shipment_id, row]));
  const latestByShipment = new Map(latestPositions.map(row => [row.shipment_id, row]));
  const roadByShipment = new Map(roadTransports.map(row => [row.shipment_id, row]));
  const orderByShipment = new Map(orderRows.map(row => [row.shipment_id, row]));
  const checkpointsByTransport = roadCheckpoints.reduce<Map<string, any[]>>((map, checkpoint) => {
    const current = map.get(checkpoint.road_transport_id) || [];
    current.push(checkpoint);
    map.set(checkpoint.road_transport_id, current);
    return map;
  }, new Map());
  return shipments.map(shipment => {
    const extra = metadataByShipment.get(shipment.shipmentId) || {};
    const road = roadByShipment.get(shipment.shipmentId);
    const order = orderByShipment.get(shipment.shipmentId);
    return {
      ...shipment,
      mmsi: extra.mmsi || null,
      vesselId: extra.vessel_id || null,
      containerType: extra.container_type || null,
      sealNo: extra.seal_no || null,
      loadedWeightKg: extra.loaded_weight_kg || null,
      loadingDate: extra.loading_date || null,
      departureDate: extra.departure_date || null,
      estimatedArrivalDate: extra.estimated_arrival_date || null,
      shippingLine: extra.shipping_line || null,
      incoterm: extra.incoterm || null,
      destinationMarket: extra.destination_market || null,
      customerOrder: order ? {
        orderId: order.order_id,
        referenceCode: order.reference_code,
        buyer: order.buyer,
        companyName: order.company_name,
        customerEmail: order.customer_email,
        customerPhone: order.customer_phone,
        weight: Number(order.weight || 0),
        grade: order.grade,
        country: order.country,
      } : null,
      latestVesselPosition: latestByShipment.get(shipment.shipmentId) || null,
      roadTransport: road ? roadTransportView(road, checkpointsByTransport.get(road.road_transport_id) || []) : null,
      ...streamSummary(shipment.shipmentId),
    };
  });
};

