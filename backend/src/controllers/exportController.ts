const defectCount = (defects: any): number => {
  if (!defects || typeof defects !== 'object') return 0;
  if (Array.isArray(defects)) return defects.reduce((sum: number, item: any) => sum + Number(item?.count || item || 0), 0);
  return Object.values(defects).reduce((sum: number, value: unknown) => sum + Number(value || 0), 0);
};

const assessmentTier = (assessment: any): string => {
  const score = Number(assessment?.cuppingScore || 0);
  const moisture = Number(assessment?.moisture || 0);
  const totalDefects = defectCount(assessment?.defects);
  if (score >= 85 && totalDefects <= 5 && moisture >= 10 && moisture <= 12) return 'Premium';
  if (score >= 75 && score < 85 && totalDefects <= 10) return 'Standard';
  return 'Low';
};

const normalizeRequirementGrade = (grade: string | null | undefined): string => {
  const value = String(grade || '').toLowerCase();
  if (value.includes('premium') || value === 'a1' || value.includes('specialty')) return 'Premium';
  if (value.includes('standard') || value === 'a2') return 'Standard';
  if (value.includes('low') || value === 'a3' || value === 'b') return 'Low';
  return grade || 'Any';
};

const parseMaxDefects = (value: any): number | null => {
  if (value === undefined || value === null || value === '') return null;
  const match = String(value).match(/\d+/);
  return match ? Number(match[0]) : null;
};

const buildBatchMatch = (order: any, batch: any) => {
  const specs = (order.qualitySpecs || {}) as Record<string, any>;
  const latestAssessment = batch.qualityAssessments?.[0] || null;
  const orderVariety = String(specs.coffeeType || specs.coffeeVariety || '').trim();
  const batchVariety = String(batch.coffeeVariety || 'Red Bourbon').trim();
  const requestedGrade = normalizeRequirementGrade(order.grade);
  const batchTier = assessmentTier(latestAssessment);
  const requestedWeight = Number(order.weight || 0);
  const availableWeight = Number(batch.availableWeightKg ?? batch.weightCherry ?? 0);
  const cuppingScore = Number(latestAssessment?.cuppingScore || 0);
  const moisture = Number(latestAssessment?.moisture || 0);
  const defects = defectCount(latestAssessment?.defects);
  const minScore = specs.minCuppingScore ? Number(specs.minCuppingScore) : null;
  const maxMoisture = specs.maxMoisture ? Number(specs.maxMoisture) : null;
  const maxDefects = parseMaxDefects(specs.defectTolerance);
  const deforestationRiskLevel = String(batch.deforestationRiskLevel || batch.deforestation_risk_level || 'NOT_VERIFIED').toUpperCase();
  const deforestationRiskScore = Number(batch.deforestationRiskScore ?? batch.deforestation_risk_score ?? 0);

  let score = 100;
  const strengths: string[] = [];
  const cautions: string[] = [];

  if (deforestationRiskLevel === 'LOW') {
    strengths.push('EUDR deforestation screening is low risk');
  } else if (deforestationRiskLevel === 'MEDIUM') {
    score -= 15;
    cautions.push('EUDR deforestation screening requires review');
  } else if (deforestationRiskLevel === 'HIGH') {
    score -= 45;
    cautions.push('High deforestation risk: review before export authorization');
  } else {
    score -= 10;
    cautions.push('EUDR deforestation screening has not been verified');
  }

  if (orderVariety) {
    if (batchVariety.toLowerCase() === orderVariety.toLowerCase()) strengths.push(`Variety matches ${orderVariety}`);
    else { score -= 35; cautions.push(`Variety is ${batchVariety}, requested ${orderVariety}`); }
  } else {
    strengths.push(`Variety available: ${batchVariety}`);
  }

  if (requestedGrade !== 'Any') {
    if (batchTier === requestedGrade) strengths.push(`Grade matches ${requestedGrade}`);
    else { score -= 25; cautions.push(`Grade is ${batchTier}, requested ${requestedGrade}`); }
  }

  if (minScore !== null && Number.isFinite(minScore)) {
    if (cuppingScore >= minScore) strengths.push(`Cupping score ${cuppingScore} meets minimum ${minScore}`);
    else { score -= 20; cautions.push(`Cupping score ${cuppingScore} is below ${minScore}`); }
  }

  if (maxMoisture !== null && Number.isFinite(maxMoisture)) {
    if (moisture <= maxMoisture) strengths.push(`Moisture ${moisture}% within target`);
    else { score -= 15; cautions.push(`Moisture ${moisture}% exceeds ${maxMoisture}%`); }
  }

  if (maxDefects !== null && Number.isFinite(maxDefects)) {
    if (defects <= maxDefects) strengths.push(`${defects} defects within tolerance`);
    else { score -= 15; cautions.push(`${defects} defects exceeds tolerance ${maxDefects}`); }
  }

  if (requestedWeight > 0) {
    if (availableWeight >= requestedWeight) strengths.push(`Single batch can cover ${requestedWeight.toLocaleString()} kg`);
    else { score -= 10; cautions.push(`Partial quantity: ${availableWeight.toLocaleString()} kg available of ${requestedWeight.toLocaleString()} kg requested`); }
  }

  score = Math.max(0, Math.min(100, score));
  const matchType = score >= 90 && availableWeight >= requestedWeight ? 'Exact Match' : score >= 70 ? 'Partial Match' : 'Needs Review';

  return {
    batchId: batch.batchId,
    qrCode: batch.qrCode,
    farmName: batch.farmName,
    washingStation: batch.washingStation,
    coffeeVariety: batchVariety,
    weightCherry: availableWeight,
    totalWeightKg: Number(batch.totalWeightKg ?? batch.weightCherry ?? 0),
    reservedWeightKg: Number(batch.reservedWeightKg || 0),
    availableWeightKg: availableWeight,
    status: batch.status,
    quality: {
      tier: batchTier,
      cuppingScore,
      moisture,
      defects,
      assessmentDate: latestAssessment?.createdAt || null,
    },
    deforestation: {
      riskLevel: deforestationRiskLevel,
      riskScore: deforestationRiskScore,
    },
    matchScore: score,
    matchType,
    reasons: [...strengths, ...cautions],
  };
};

export const getOrderMatchingBatches = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const orderId = String(req.params.orderId || '');
    const order = await prisma.exportOrder.findUnique({ where: { orderId } });
    if (!order) {
      res.status(404).json({ message: 'Export order not found.' });
      return;
    }
    const batches = await prisma.coffeeBatch.findMany({
      where: { status: { in: ['export_ready', 'shipment_authorized'] }, qualityAssessments: { some: {} } },
      include: { qualityAssessments: { orderBy: { createdAt: 'desc' }, take: 1 } },
      orderBy: { createdAt: 'desc' },
      take: 100,
    });
    await ensureExportOrderAllocationStorage();
    const reservedRows = batches.length
      ? await prisma.$queryRawUnsafe<Array<{ batch_id: string; reserved_kg: any }>>(
          `SELECT eoba.batch_id, COALESCE(SUM(eoba.allocated_weight_kg), 0) AS reserved_kg
           FROM export_order_batch_allocations eoba
           JOIN export_orders eo ON eo.order_id = eoba.order_id
           WHERE eoba.batch_id IN (${batches.map(batch => `'${batch.batchId.replace(/'/g, "''")}'`).join(',')})
             AND eoba.order_id <> '${orderId.replace(/'/g, "''")}'
             AND LOWER(eo.status) NOT IN ('rejected', 'delivered', 'cancelled', 'canceled')
           GROUP BY eoba.batch_id`
        )
      : [];
    const reservedByBatch = new Map(reservedRows.map(row => [row.batch_id, Number(row.reserved_kg || 0)]));
    const riskRows = batches.length
      ? await prisma.$queryRawUnsafe<Array<{ batch_id: string; deforestation_risk_level: string | null; deforestation_risk_score: number | null }>>(
          `SELECT batch_id, deforestation_risk_level, deforestation_risk_score
           FROM coffee_batches
           WHERE batch_id IN (${batches.map(batch => `'${batch.batchId.replace(/'/g, "''")}'`).join(',')})`
        )
      : [];
    const riskByBatch = new Map(riskRows.map(row => [row.batch_id, row]));
    const matches = batches
      .map(batch => {
        const totalWeightKg = Number(batch.weightCherry || 0);
        const reservedWeightKg = reservedByBatch.get(batch.batchId) || 0;
        const risk = riskByBatch.get(batch.batchId);
        return buildBatchMatch(order, {
          ...batch,
          totalWeightKg,
          reservedWeightKg,
          availableWeightKg: Math.max(0, totalWeightKg - reservedWeightKg),
          deforestationRiskLevel: risk?.deforestation_risk_level || null,
          deforestationRiskScore: risk?.deforestation_risk_score || null,
        });
      })
      .filter(match => Number(match.availableWeightKg || match.weightCherry || 0) > 0)
      .sort((a, b) => b.matchScore - a.matchScore || Number(b.weightCherry || 0) - Number(a.weightCherry || 0));

    res.status(200).json({
      success: true,
      data: {
        order: {
          orderId: order.orderId,
          referenceCode: order.referenceCode,
          buyer: order.buyer,
          requestedWeightKg: Number(order.weight || 0),
          requestedGrade: order.grade,
          requestedVariety: (order.qualitySpecs as any)?.coffeeType || (order.qualitySpecs as any)?.coffeeVariety || null,
        },
        matches,
      },
    });
  } catch (error) {
    console.error('Error matching export order:', error);
    res.status(500).json({ message: 'Server error finding matching batches' });
  }
};

export const allocateOrderBatches = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    await ensureExportOrderAllocationStorage();
    const orderId = String(req.params.orderId || '');
    const allocations = Array.isArray(req.body?.allocations) ? req.body.allocations : [];
    if (allocations.length === 0) {
      res.status(400).json({ message: 'At least one batch allocation is required.' });
      return;
    }
    const order = await prisma.exportOrder.findUnique({ where: { orderId } });
    if (!order) {
      res.status(404).json({ message: 'Export order not found.' });
      return;
    }
    const selectedIds = allocations.map((row: any) => String(row.batchId)).filter(Boolean);
    if (new Set(selectedIds).size !== selectedIds.length) {
      res.status(400).json({ message: 'Each batch can only appear once in an order allocation.' });
      return;
    }
    const selectedBatches = await prisma.coffeeBatch.findMany({
      where: { batchId: { in: selectedIds }, status: { in: ['export_ready', 'shipment_authorized'] }, qualityAssessments: { some: {} } },
      include: { qualityAssessments: { orderBy: { createdAt: 'desc' }, take: 1 } },
    });
    if (selectedBatches.length !== selectedIds.length) {
      res.status(400).json({ message: 'Only quality-certified export-ready batches can be allocated.' });
      return;
    }

    const riskRows = selectedBatches.length
      ? await prisma.$queryRawUnsafe<Array<{ batch_id: string; deforestation_risk_level: string | null; deforestation_risk_score: number | null }>>(
          `SELECT batch_id, deforestation_risk_level, deforestation_risk_score
           FROM coffee_batches
           WHERE batch_id IN (${selectedBatches.map(batch => `'${batch.batchId.replace(/'/g, "''")}'`).join(',')})`
        )
      : [];
    const riskByBatch = new Map(riskRows.map(row => [row.batch_id, row]));
    const matchByBatch = new Map(selectedBatches.map(batch => {
      const risk = riskByBatch.get(batch.batchId);
      return [batch.batchId, buildBatchMatch(order, {
        ...batch,
        deforestationRiskLevel: risk?.deforestation_risk_level || null,
        deforestationRiskScore: risk?.deforestation_risk_score || null,
      })];
    }));
    const blockedRiskMatch = Array.from(matchByBatch.values()).find((match: any) => match.deforestation?.riskLevel === 'HIGH');
    if (blockedRiskMatch) {
      res.status(400).json({ message: `Batch ${blockedRiskMatch.qrCode} has HIGH deforestation risk and must be reviewed before export authorization.` });
      return;
    }
    const requestedWeight = Number(order.weight || 0);
    const explicitAllocationTotal = allocations.reduce((sum: number, row: any) => sum + Math.max(0, Number(row.allocatedWeightKg || 0)), 0);
    if (requestedWeight > 0 && explicitAllocationTotal - requestedWeight > 0.01) {
      res.status(400).json({ message: `Selected quantity cannot exceed the order request of ${requestedWeight} kg.` });
      return;
    }
    const inserted = await prisma.$transaction(async (tx) => {
      const quotedBatchIds = selectedIds.map((id: string) => `'${id.replace(/'/g, "''")}'`).join(',');
      await tx.$queryRawUnsafe(`SELECT batch_id FROM coffee_batches WHERE batch_id IN (${quotedBatchIds}) FOR UPDATE`);
      const reservedRows = await tx.$queryRawUnsafe<Array<{ batch_id: string; reserved_kg: any }>>(
        `SELECT eoba.batch_id, COALESCE(SUM(eoba.allocated_weight_kg), 0) AS reserved_kg
         FROM export_order_batch_allocations eoba
         JOIN export_orders eo ON eo.order_id = eoba.order_id
         WHERE eoba.batch_id IN (${quotedBatchIds})
           AND eoba.order_id <> '${orderId.replace(/'/g, "''")}'
           AND LOWER(eo.status) NOT IN ('rejected', 'delivered', 'cancelled', 'canceled')
         GROUP BY eoba.batch_id`
      );
      const reservedByBatch = new Map(reservedRows.map(row => [row.batch_id, Number(row.reserved_kg || 0)]));
      let remaining = requestedWeight;
      await tx.$executeRawUnsafe(`DELETE FROM export_order_batch_allocations WHERE order_id = $1`, orderId);
      const rows: any[] = [];
      for (const row of allocations) {
        const batchId = String(row.batchId);
        const baseMatch = matchByBatch.get(batchId);
        if (!baseMatch) continue;
        const totalWeightKg = Number(baseMatch.weightCherry || 0);
        const reservedWeightKg = reservedByBatch.get(batchId) || 0;
        const availableWeightKg = Math.max(0, totalWeightKg - reservedWeightKg);
        const requestedAllocation = Number(row.allocatedWeightKg || 0);
        if (requestedAllocation - availableWeightKg > 0.01) {
          throw new Error(`ALLOCATION_CONFLICT:Batch ${baseMatch.qrCode} has only ${availableWeightKg} kg available.`);
        }
        if (requestedWeight > 0 && remaining <= 0) break;
        const allocatedWeight = requestedAllocation > 0
          ? Math.min(requestedAllocation, availableWeightKg, requestedWeight > 0 ? remaining : availableWeightKg)
          : Math.min(requestedWeight > 0 ? remaining : availableWeightKg, availableWeightKg);
        if (allocatedWeight <= 0) continue;
        remaining -= allocatedWeight;
        const match = {
          ...baseMatch,
          totalWeightKg,
          reservedWeightKg,
          availableWeightKg,
        };
        const allocationId = `ALC-${Date.now()}-${randomBytes(4).toString('hex')}`;
        await tx.$executeRawUnsafe(
          `INSERT INTO export_order_batch_allocations
             (allocation_id, order_id, batch_id, allocated_weight_kg, match_score, match_type, created_by)
           VALUES ($1, $2, $3, $4, $5, $6, $7)
           ON CONFLICT (order_id, batch_id) DO UPDATE SET
             allocated_weight_kg = EXCLUDED.allocated_weight_kg,
             match_score = EXCLUDED.match_score,
             match_type = EXCLUDED.match_type,
             created_by = EXCLUDED.created_by,
             created_at = NOW()`,
          allocationId,
          orderId,
          batchId,
          allocatedWeight,
          Number(match.matchScore || 0),
          match.matchType,
          req.user?.userId || null
        );
        rows.push({ ...match, allocatedWeightKg: allocatedWeight });
      }
      return rows;
    });
    const allocatedTotal = inserted.reduce((sum, row) => sum + Number(row.allocatedWeightKg || 0), 0);
    const status = requestedWeight > 0 && allocatedTotal >= requestedWeight ? 'Matched / Ready for Quote' : 'Partially Matched';
    const updatedOrder = await prisma.exportOrder.update({
      where: { orderId },
      data: { status, batchId: inserted[0]?.batchId || order.batchId || null },
      include: { messages: { orderBy: { createdAt: 'asc' } } },
    });
    await prisma.auditLog.create({
      data: {
        userId: req.user?.userId,
        action: 'EXPORT_ORDER_BATCHES_ALLOCATED',
        entityType: 'ExportOrder',
        entityId: orderId,
        details: { allocatedTotal, requestedWeight, status, batchIds: inserted.map(row => row.batchId) },
        ipAddress: req.ip,
      },
    });
    res.status(200).json({ success: true, data: { order: updatedOrder, allocations: inserted, allocatedTotal, status } });
  } catch (error) {
    console.error('Error allocating export order batches:', error);
    if (error instanceof Error && error.message.startsWith('ALLOCATION_CONFLICT:')) {
      res.status(409).json({ message: error.message.replace('ALLOCATION_CONFLICT:', '') });
      return;
    }
    res.status(500).json({ message: 'Server error allocating matching batches' });
  }
};

