const createSimplePdfDataUrl = (title: string, sections: Array<{ heading: string; rows: Array<[string, any]> }>) => {
  const operations: string[] = [];
  let y = 800;
  const addText = (text: string, x = 50, size = 10, leading = 16) => {
    if (y < 55) return;
    operations.push(`BT /F1 ${size} Tf ${x} ${y} Td (${pdfEscape(text)}) Tj ET`);
    y -= leading;
  };
  addText('IMPEXCOR Ltd', 50, 18, 22);
  addText(title, 50, 14, 24);
  addText(`Generated: ${new Date().toLocaleString('en-GB')}`, 50, 9, 20);
  sections.forEach(section => {
    addText(section.heading, 50, 12, 18);
    section.rows.forEach(([label, value]) => addText(`${label}: ${value}`, 65, 10, 14));
    y -= 8;
  });
  addText('This document was generated by the Smart Coffee Supply Chain Management System.', 50, 8, 12);
  const stream = operations.join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${Buffer.byteLength(stream, 'utf8')} >>\nstream\n${stream}\nendstream`,
  ];
  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(pdf, 'utf8'));
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefOffset = Buffer.byteLength(pdf, 'utf8');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.slice(1).forEach(offset => {
    pdf += `${String(offset).padStart(10, '0')} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return `data:application/pdf;base64,${Buffer.from(pdf, 'utf8').toString('base64')}`;
};
