export const startVesselTracking = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    await ensureVesselTrackingStorage();
    const shipmentId = req.params.shipmentId as string;
    const suppliedMmsi = String(req.body.mmsi || '').trim();
    const shipmentRows = await prisma.$queryRaw<Array<any>>`
      SELECT shipment_id, container_no, vessel_name, mmsi FROM shipping_records WHERE shipment_id = ${shipmentId}
    `;
    const shipment = shipmentRows[0];
    if (!shipment) {
      res.status(404).json({ message: 'Shipment not found' });
      return;
    }
    const mmsi = suppliedMmsi || shipment.mmsi;
    if (!validMmsi(mmsi)) {
      res.status(400).json({ message: 'A valid 9-digit vessel MMSI is required to start AIS tracking' });
      return;
    }
    const apiKey = process.env.AISSTREAM_API_KEY;
    if (!apiKey) {
      res.status(503).json({ message: 'AISStream is not configured. Add AISSTREAM_API_KEY to backend environment settings.' });
      return;
    }
    const RuntimeWebSocket = (globalThis as any).WebSocket;
    if (!RuntimeWebSocket) {
      res.status(503).json({ message: 'The server runtime does not support WebSocket connections for AIS tracking.' });
      return;
    }
    const prior = activeAisStreams.get(shipmentId);
    if (prior) prior.socket.close();
    await prisma.$executeRaw`UPDATE shipping_records SET mmsi = ${mmsi} WHERE shipment_id = ${shipmentId}`;
    const socket = new RuntimeWebSocket('wss://stream.aisstream.io/v0/stream');
    const session: AisSession = {
      socket,
      mmsi,
      startedAt: new Date(),
      connectionStatus: 'connecting',
      receivedPositions: 0,
    };
    activeAisStreams.set(shipmentId, session);

    socket.addEventListener('open', () => {
      session.connectionStatus = 'waiting_for_transmission';
      socket.send(JSON.stringify({
        APIKey: apiKey,
        BoundingBoxes: [[[-90, -180], [90, 180]]],
        FiltersShipMMSI: [mmsi],
        FilterMessageTypes: ['PositionReport', 'StandardClassBPositionReport', 'ExtendedClassBPositionReport'],
      }));
    });
    socket.addEventListener('message', async (event: any) => {
      try {
        const payload = typeof event.data === 'string'
          ? event.data
          : typeof event.data?.text === 'function'
            ? await event.data.text()
            : String(event.data);
        const message = JSON.parse(payload);
        const body = message.Message?.[message.MessageType] || {};
        const metadata = message.MetaData || message.Metadata || {};
        const latitude = Number(body.Latitude ?? metadata.Latitude ?? metadata.latitude);
        const longitude = Number(body.Longitude ?? metadata.Longitude ?? metadata.longitude);
        if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) return;
        const metadataTime = metadata.time_utc ? new Date(metadata.time_utc) : null;
        const positionTime = metadataTime && Number.isFinite(metadataTime.getTime()) ? metadataTime : new Date();
        await prisma.$executeRaw`
          INSERT INTO vessel_tracking_positions (
            shipment_id, mmsi, vessel_name, latitude, longitude, speed_over_ground,
            course_over_ground, true_heading, navigation_status, position_time, source
          )
          VALUES (
            ${shipmentId}, ${mmsi}, ${metadata.ShipName || metadata.shipName || shipment.vessel_name || null},
            ${latitude}, ${longitude}, ${Number.isFinite(Number(body.Sog)) ? Number(body.Sog) : null},
            ${Number.isFinite(Number(body.Cog)) ? Number(body.Cog) : null},
            ${Number.isFinite(Number(body.TrueHeading)) ? Number(body.TrueHeading) : null},
            ${body.NavigationalStatus !== undefined ? String(body.NavigationalStatus) : null},
            ${positionTime}, 'AISStream'
          )
        `;
        session.connectionStatus = 'receiving_positions';
        session.receivedPositions += 1;
        session.lastMessageAt = new Date();
      } catch (error) {
        console.error('AISStream message processing error:', error);
        session.lastError = 'An AIS message could not be processed.';
      }
    });
    socket.addEventListener('close', () => {
      if (activeAisStreams.get(shipmentId)?.socket === socket) session.connectionStatus = 'closed';
    });
    socket.addEventListener('error', () => {
      if (activeAisStreams.get(shipmentId)?.socket === socket) {
        session.connectionStatus = 'error';
        session.lastError = 'AISStream connection failed.';
      }
    });
    await prisma.auditLog.create({
      data: {
        userId: req.user?.userId,
        action: 'AIS_VESSEL_TRACKING_STARTED',
        entityType: 'ShippingRecord',
        entityId: shipmentId,
        details: { mmsi, provider: 'AISStream' },
        ipAddress: req.ip,
      }
    });
    res.status(202).json({ success: true, data: { shipmentId, mmsi, trackingActive: true, connectionStatus: session.connectionStatus } });
  } catch (error) {
    console.error('Error starting vessel tracking:', error);
    res.status(500).json({ message: 'Server error starting vessel tracking' });
  }
};

