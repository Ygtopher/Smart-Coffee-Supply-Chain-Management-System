const getVesselFinderFleetPositions = async () => {
  const apiKey = String(process.env.VESSELFINDER_API_KEY || '').trim();
  if (!apiKey) {
    return { configured: false, positions: [] as AisMonitorPosition[] };
  }
  const endpoint = new URL('https://api.vesselfinder.com/vesselslist');
  endpoint.searchParams.set('userkey', apiKey);
  endpoint.searchParams.set('format', 'json');
  const response = await fetch(endpoint.toString());
  if (!response.ok) {
    throw new Error(`VesselFinder returned HTTP ${response.status}`);
  }
  const records = await response.json() as Array<{ AIS?: Record<string, any> }>;
  const positions = (Array.isArray(records) ? records : []).flatMap(record => {
    const ais = record.AIS;
    const latitude = Number(ais?.LATITUDE);
    const longitude = Number(ais?.LONGITUDE);
    if (!ais || !Number.isFinite(latitude) || !Number.isFinite(longitude)) return [];
    const timestamp = ais.TIMESTAMP ? new Date(String(ais.TIMESTAMP).replace(' UTC', 'Z')) : new Date();
    return [{
      mmsi: String(ais.MMSI || ''),
      vessel_name: ais.NAME ? String(ais.NAME) : null,
      latitude,
      longitude,
      speed_over_ground: Number.isFinite(Number(ais.SPEED)) ? Number(ais.SPEED) : null,
      course_over_ground: Number.isFinite(Number(ais.COURSE)) ? Number(ais.COURSE) : null,
      true_heading: Number.isFinite(Number(ais.HEADING)) ? Number(ais.HEADING) : null,
      navigation_status: ais.NAVSTAT !== undefined ? String(ais.NAVSTAT) : null,
      position_time: Number.isFinite(timestamp.getTime()) ? timestamp : new Date(),
      source: 'VesselFinder',
      destination: ais.DESTINATION ? String(ais.DESTINATION) : null,
      eta: ais.ETA ? String(ais.ETA) : null,
    }];
  });
  return { configured: true, positions };
};

const getDataDockedVesselLocation = async (identifier: string) => {
  const apiKey = String(process.env.DATADOCKED_API_KEY || '').trim();
  if (!apiKey) {
    return { configured: false, position: null, creditsRemaining: null, cached: false };
  }
  const cachedLocation = dataDockedPositionCache.get(identifier);
  if (cachedLocation && Date.now() - cachedLocation.fetchedAt.getTime() < VESSEL_LOCATION_CACHE_MS) {
    return { configured: true, position: cachedLocation.position, creditsRemaining: null, cached: true };
  }
  const creditResponse = await fetch('https://datadocked.com/api/vessels_operations/my-credits', {
    headers: { accept: 'application/json', 'x-api-key': apiKey },
  });
  if (!creditResponse.ok) {
    throw new Error(`Data Docked credit check returned HTTP ${creditResponse.status}`);
  }
  const creditBody = await creditResponse.json() as { detail?: { credits?: number } };
  const creditsRemaining = Number(creditBody.detail?.credits ?? 0);
  if (creditsRemaining < 1) {
    return {
      configured: true,
      position: cachedLocation?.position || null,
      creditsRemaining,
      cached: Boolean(cachedLocation),
    };
  }
  const endpoint = new URL('https://datadocked.com/api/vessels_operations/get-vessel-location');
  endpoint.searchParams.set('imo_or_mmsi', identifier);
  const response = await fetch(endpoint.toString(), {
    headers: {
      accept: 'application/json',
      'x-api-key': apiKey,
    },
  });
  if (!response.ok) {
    throw new Error(`Data Docked returned HTTP ${response.status}`);
  }
  const body = await response.json() as Record<string, any>;
  const detail = body.detail || body;
  const latitude = Number(detail.latitude);
  const longitude = Number(detail.longitude);
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) {
    return { configured: true, position: null, creditsRemaining: creditsRemaining - 1, cached: false };
  }
  const position = {
      identifier,
      mmsi: detail.mmsi ? String(detail.mmsi) : null,
      imo: detail.imo ? String(detail.imo) : null,
      vessel_name: detail.name ? String(detail.name) : null,
      latitude,
      longitude,
      speed_over_ground: detail.speed ?? null,
      course_over_ground: detail.course ?? null,
      true_heading: detail.heading ?? null,
      navigation_status: detail.navigationalStatus ?? null,
      destination: detail.destination ?? null,
      eta: detail.etaUtc ?? null,
      position_time: detail.positionReceived || detail.updateTime || null,
      source: detail.dataSource ? `Data Docked - ${detail.dataSource}` : 'Data Docked',
  };
  dataDockedPositionCache.set(identifier, { position, fetchedAt: new Date() });
  return {
    configured: true,
    position,
    creditsRemaining: Math.max(creditsRemaining - 1, 0),
    cached: false,
  };
};

