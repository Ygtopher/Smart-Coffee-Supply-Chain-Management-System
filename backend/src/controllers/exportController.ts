export const startLiveVesselDiscovery = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const apiKey = process.env.AISSTREAM_API_KEY;
    if (!apiKey) {
      res.status(503).json({ message: 'AISStream is not configured. Add AISSTREAM_API_KEY to backend environment settings.' });
      return;
    }
    const RuntimeWebSocket = (globalThis as any).WebSocket;
    if (!RuntimeWebSocket) {
      res.status(503).json({ message: 'The server runtime does not support WebSocket connections for AIS tracking.' });
      return;
    }
    const running = activeAisDiscoveries.get(AIS_DISCOVERY_AREA);
    if (running && !['closed', 'error'].includes(running.connectionStatus)) {
      res.status(200).json({ success: true, data: discoverySummary() });
      return;
    }
    const socket = new RuntimeWebSocket('wss://stream.aisstream.io/v0/stream');
    const session: AisDiscoverySession = {
      socket,
      mmsi: AIS_DISCOVERY_AREA,
      areaName: AIS_DISCOVERY_AREA_NAME,
      startedAt: new Date(),
      connectionStatus: 'connecting',
      receivedPositions: 0,
      positions: running?.positions || new Map<string, AisMonitorPosition>(),
    };
    activeAisDiscoveries.set(AIS_DISCOVERY_AREA, session);

    socket.addEventListener('open', () => {
      session.connectionStatus = 'waiting_for_transmission';
      socket.send(JSON.stringify({
        APIKey: apiKey,
        BoundingBoxes: AIS_DISCOVERY_BOUNDING_BOXES,
        FilterMessageTypes: ['PositionReport', 'StandardClassBPositionReport', 'ExtendedClassBPositionReport'],
      }));
    });
    socket.addEventListener('message', async (event: any) => {
      try {
        const payload = typeof event.data === 'string'
          ? event.data
          : typeof event.data?.text === 'function'
            ? await event.data.text()
            : String(event.data);
        const message = JSON.parse(payload);
        if (message.error || message.Error || message.MessageType === 'Error') {
          session.connectionStatus = 'error';
          session.lastError = String(message.error || message.Error || 'AISStream rejected the live traffic subscription.');
          return;
        }
        const body = message.Message?.[message.MessageType] || {};
        const metadata = message.MetaData || message.Metadata || {};
        const mmsi = String(body.UserID ?? metadata.MMSI ?? metadata.mmsi ?? '').trim();
        const latitude = Number(body.Latitude ?? metadata.Latitude ?? metadata.latitude);
        const longitude = Number(body.Longitude ?? metadata.Longitude ?? metadata.longitude);
        if (!validMmsi(mmsi) || !Number.isFinite(latitude) || !Number.isFinite(longitude)) return;
        const metadataTime = metadata.time_utc ? new Date(metadata.time_utc) : null;
        const positionTime = metadataTime && Number.isFinite(metadataTime.getTime()) ? metadataTime : new Date();
        session.positions.clear();
        session.positions.set(mmsi, {
          mmsi,
          vessel_name: metadata.ShipName || metadata.shipName || session.positions.get(mmsi)?.vessel_name || null,
          latitude,
          longitude,
          speed_over_ground: Number.isFinite(Number(body.Sog)) ? Number(body.Sog) : null,
          course_over_ground: Number.isFinite(Number(body.Cog)) ? Number(body.Cog) : null,
          true_heading: Number.isFinite(Number(body.TrueHeading)) ? Number(body.TrueHeading) : null,
          navigation_status: body.NavigationalStatus !== undefined ? String(body.NavigationalStatus) : null,
          position_time: positionTime,
          source: 'AISStream',
        });
        session.connectionStatus = 'receiving_positions';
        session.receivedPositions += 1;
        session.lastMessageAt = new Date();
      } catch (error) {
        console.error('AIS vessel discovery message processing error:', error);
        session.lastError = 'An AIS discovery message could not be processed.';
      }
    });
    socket.addEventListener('close', () => {
      if (activeAisDiscoveries.get(AIS_DISCOVERY_AREA)?.socket === socket && session.receivedPositions === 0) session.connectionStatus = 'closed';
    });
    socket.addEventListener('error', () => {
      if (activeAisDiscoveries.get(AIS_DISCOVERY_AREA)?.socket === socket) {
        session.connectionStatus = 'error';
        session.lastError = 'AISStream discovery connection failed.';
      }
    });
    await prisma.auditLog.create({
      data: {
        userId: req.user?.userId,
        action: 'AIS_LIVE_VESSEL_DISCOVERY_STARTED',
        entityType: 'VesselMonitor',
        entityId: AIS_DISCOVERY_AREA,
        details: { provider: 'AISStream', areaName: AIS_DISCOVERY_AREA_NAME },
        ipAddress: req.ip,
      }
    });
    res.status(202).json({ success: true, data: discoverySummary() });
  } catch (error) {
    console.error('Error starting AIS vessel discovery:', error);
    res.status(500).json({ message: 'Server error starting live vessel discovery' });
  }
};

