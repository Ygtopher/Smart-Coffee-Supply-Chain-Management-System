export const createShippingRecord = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    await ensureVesselTrackingStorage();
    const {
      batchId, batchIds, containerNo, vesselId, vesselName: submittedVesselName, portLoading: submittedPortLoading, portDestination,
      shippingLine, incoterm, quotedFreightCost, actualFreightCost, insuranceDetails,
      customsStatus, naebLicense, eudrVerifiedLoc, destinationMarket, mmsi: submittedMmsi,
      containerType, sealNo, loadedWeightKg, loadingDate, departureDate, estimatedArrivalDate, orderId
    } = req.body;
    if ((!batchId && !orderId) || !String(containerNo || '').trim() || !String(portDestination || '').trim()) {
      res.status(400).json({ message: 'Export-ready batch, container number and destination port are required.' });
      return;
    }
    let authorizedOrder = null as any;
    let shipmentBatchIds = [String(batchId)].filter(Boolean);
    let maxLoadWeight = 0;
    if (orderId) {
      await ensureExportOrderAllocationStorage();
      authorizedOrder = await prisma.exportOrder.findUnique({ where: { orderId: String(orderId) } });
      const requestedBatchIds = (Array.isArray(batchIds) ? batchIds : shipmentBatchIds)
        .map((id: any) => String(id || '').trim())
        .filter(Boolean);
      const batchFilter = requestedBatchIds.length
        ? `AND batch_id IN (${requestedBatchIds.map((id: string) => `'${id.replace(/'/g, "''")}'`).join(',')})`
        : 'AND shipment_id IS NULL';
      const allocationRows = await prisma.$queryRawUnsafe<Array<{ batch_id: string; allocated_weight_kg: any; shipment_id: string | null }>>(
        `SELECT batch_id, allocated_weight_kg, shipment_id
         FROM export_order_batch_allocations
         WHERE order_id = '${String(orderId).replace(/'/g, "''")}'
         ${batchFilter}
         ORDER BY created_at ASC`
      );
      if (!authorizedOrder || !['Ready for Shipment', 'Logistics Authorized', 'Shipment Created'].includes(String(authorizedOrder.status)) || allocationRows.length === 0) {
        res.status(400).json({ message: 'Select a customer order that was authorized by Exporter for shipment.' });
        return;
      }
      if (allocationRows.some(row => row.shipment_id)) {
        res.status(409).json({ message: 'One or more authorized order allocations already have a shipment.' });
        return;
      }
      shipmentBatchIds = allocationRows.map(row => String(row.batch_id));
      maxLoadWeight = allocationRows.reduce((sum, row) => sum + Number(row.allocated_weight_kg || 0), 0);
    } else {
      const batch = await prisma.coffeeBatch.findUnique({ where: { batchId: String(batchId) } });
      if (!batch || batch.status !== 'shipment_authorized') {
        res.status(400).json({ message: 'Only a batch authorized by Exporter can be assigned to a new shipment.' });
        return;
      }
      maxLoadWeight = Number(batch.weightCherry);
      const existingShipment = await prisma.shippingRecord.findFirst({
        where: { batchId: String(batchId), status: { notIn: ['Cancelled', 'Rejected'] } }
      });
      if (existingShipment) {
        res.status(409).json({ message: 'This batch is already assigned to an active shipment.' });
        return;
      }
    }
    const shipmentBatches = await prisma.coffeeBatch.findMany({ where: { batchId: { in: shipmentBatchIds } } });
    if (shipmentBatches.length !== shipmentBatchIds.length || shipmentBatches.some(batch => batch.status !== 'shipment_authorized')) {
      res.status(400).json({ message: 'Only batches authorized by Exporter can be assigned to a new shipment.' });
      return;
    }
    const primaryBatchId = shipmentBatchIds[0];
    const submittedWeight = Number(loadedWeightKg || maxLoadWeight);
    if (!Number.isFinite(submittedWeight) || submittedWeight <= 0 || submittedWeight - maxLoadWeight > 0.01) {
      res.status(400).json({ message: 'Loaded weight cannot exceed the exporter-authorized quantity for this shipment.' });
      return;
    }
    let vesselName = submittedVesselName || 'Pending road transport assignment';
    let portLoading = submittedPortLoading || 'IMPEXCOR Export Warehouse';
    let mmsi = submittedMmsi;
    let selectedShippingLine = shippingLine;
    if (vesselId) {
      const vessels = await prisma.$queryRaw<Array<any>>`
        SELECT vessel_id, vessel_name, mmsi, shipping_line, home_port, status FROM logistics_vessels WHERE vessel_id = ${String(vesselId)}
      `;
      const vessel = vessels[0];
      if (!vessel || vessel.status !== 'Available') {
        res.status(400).json({ message: 'Select a registered vessel marked Available before booking' });
        return;
      }
      vesselName = vessel.vessel_name;
      mmsi = vessel.mmsi;
      selectedShippingLine = vessel.shipping_line;
      portLoading = submittedPortLoading || vessel.home_port || 'Mombasa';
    }
    if (mmsi && !validMmsi(mmsi)) {
      res.status(400).json({ message: 'MMSI must contain exactly 9 digits' });
      return;
    }

    const record = await prisma.shippingRecord.create({
      data: { batchId: primaryBatchId, containerNo: String(containerNo).trim(), vesselName, portLoading, portDestination, status: 'Ready for Dispatch' }
    });
    if (mmsi) {
      await prisma.$executeRaw`UPDATE shipping_records SET mmsi = ${String(mmsi).trim()} WHERE shipment_id = ${record.shipmentId}`;
    }
    if (vesselId) {
      await prisma.$executeRaw`UPDATE shipping_records SET vessel_id = ${String(vesselId)} WHERE shipment_id = ${record.shipmentId}`;
      await prisma.$executeRaw`UPDATE logistics_vessels SET status = 'Reserved', updated_at = NOW() WHERE vessel_id = ${String(vesselId)}`;
    }
    if (authorizedOrder) {
      await prisma.$executeRawUnsafe(
        `UPDATE export_order_batch_allocations
         SET shipment_id = $1
         WHERE order_id = $2 AND batch_id IN (${shipmentBatchIds.map(id => `'${id.replace(/'/g, "''")}'`).join(',')})`,
        record.shipmentId,
        String(orderId)
      );
      await prisma.exportOrder.update({
        where: { orderId: String(orderId) },
        data: { status: 'Shipment Created', shipmentId: record.shipmentId },
      });
    }
    await prisma.$executeRaw`
      UPDATE shipping_records SET
        container_type = ${containerType ? String(containerType).trim() : '20 ft'},
        seal_no = ${sealNo ? String(sealNo).trim() : null},
        loaded_weight_kg = ${submittedWeight},
        loading_date = ${loadingDate ? new Date(loadingDate) : null},
        departure_date = ${departureDate ? new Date(departureDate) : null},
        estimated_arrival_date = ${estimatedArrivalDate ? new Date(estimatedArrivalDate) : null},
        shipping_line = ${selectedShippingLine ? String(selectedShippingLine).trim() : null},
        incoterm = ${incoterm ? String(incoterm).trim() : null},
        destination_market = ${destinationMarket ? String(destinationMarket).trim() : null}
      WHERE shipment_id = ${record.shipmentId}
    `;

    await prisma.coffeeBatch.updateMany({ where: { batchId: { in: shipmentBatchIds } }, data: { status: 'Export Scheduled' } });
    await prisma.auditLog.create({
      data: {
        userId: req.user?.userId,
        action: 'SHIPMENT_BOOKED',
        entityType: 'ShippingRecord',
        entityId: record.shipmentId,
        details: {
          containerNo,
          containerType: containerType || '20 ft',
          sealNo: sealNo || null,
          loadedWeightKg: submittedWeight,
          loadingDate: loadingDate || null,
          portDestination,
          destinationMarket: destinationMarket || null,
          orderId: orderId || null,
          batchIds: shipmentBatchIds,
          customer: authorizedOrder ? {
            buyer: authorizedOrder.buyer,
            customerEmail: authorizedOrder.customerEmail,
            customerPhone: authorizedOrder.customerPhone,
            referenceCode: authorizedOrder.referenceCode,
          } : null,
          nextSteps: ['Road Transport', 'Customs Documents'],
        },
        ipAddress: req.ip,
      }
    });
    await notifyRoles(['ADMIN', 'EXPORTER'], 'Shipment Created', `Container ${containerNo} has been created for ${portDestination}. Road transport and customs documents can now be completed.`, 'success');

    res.status(201).json({ success: true, data: { ...record, mmsi: mmsi || null } });
  } catch (error) {
    console.error('Error creating shipping record:', error);
    res.status(500).json({ message: 'Server error scheduling export' });
  }
};

