export const createDriverRoadCheckpoint = async (req: Request, res: Response): Promise<void> => {
  try {
    await ensureRoadTraceabilityStorage();
    const accessToken = String(req.params.accessToken || '').trim();
    const { checkpointName, latitude, longitude, locationAccuracyM, eventType, sealCondition, notes, driverName, driverPhone } = req.body;
    const numericLatitude = Number(latitude);
    const numericLongitude = Number(longitude);
    const numericAccuracy = Number(locationAccuracyM);
    if (!String(checkpointName || '').trim() || !String(eventType || '').trim()) {
      res.status(400).json({ message: 'Checkpoint location and event type are required.' });
      return;
    }
    if (!Number.isFinite(numericLatitude) || !Number.isFinite(numericLongitude) || !Number.isFinite(numericAccuracy)) {
      res.status(400).json({ message: 'Phone GPS coordinates and accuracy are required for a driver checkpoint.' });
      return;
    }
    const roadRows = await prisma.$queryRaw<Array<any>>`
      SELECT road.*, batch.qr_code
      FROM road_transport_records road
      JOIN shipping_records shipment ON shipment.shipment_id = road.shipment_id
      JOIN coffee_batches batch ON batch.batch_id = shipment.batch_id
      WHERE road.driver_access_token = ${accessToken}
        AND (road.driver_access_expires_at IS NULL OR road.driver_access_expires_at > NOW())
    `;
    const road = roadRows[0];
    if (!road) {
      res.status(404).json({ message: 'This driver trip link is invalid or expired.' });
      return;
    }
    if (!String(driverName || road.driver_name || '').trim()) {
      res.status(400).json({ message: 'Driver name is required for the truck company checkpoint submission.' });
      return;
    }
    const eventStatuses: Record<string, string> = {
      'Dispatch from Kigali': 'Dispatched',
      'Border Exit': 'At Border',
      'Border Entry': 'In Transit',
      'Transit Checkpoint': 'In Transit',
      'Port Arrival': 'At Port',
      'Vessel Loading': 'Loaded',
    };
    if (!eventStatuses[String(eventType)]) {
      res.status(400).json({ message: 'Invalid driver checkpoint event.' });
      return;
    }
    const roadStatus = eventStatuses[String(eventType)];
    const submittedDriverName = String(driverName || road.driver_name || '').trim();
    const submittedDriverPhone = driverPhone ? String(driverPhone).trim() : (road.driver_phone || null);
    const checkpointRows = await prisma.$queryRaw<Array<any>>`
      INSERT INTO road_transit_checkpoints (
        road_transport_id, checkpoint_name, scan_code, latitude, longitude,
        location_accuracy_m, event_type, seal_condition, submission_source,
        submitted_ip, recorded_at, notes
      ) VALUES (
        ${road.road_transport_id}, ${String(checkpointName).trim()}, ${road.qr_code || null},
        ${numericLatitude}, ${numericLongitude}, ${numericAccuracy},
        ${String(eventType)}, ${sealCondition ? String(sealCondition) : 'Intact'},
        ${'DRIVER_PHONE'}, ${req.ip || null}, ${new Date()},
        ${notes ? String(notes).trim() : null}
      )
      RETURNING *
    `;
    await prisma.$executeRaw`
      UPDATE road_transport_records SET
        driver_name = ${submittedDriverName},
        driver_phone = ${submittedDriverPhone},
        status = ${roadStatus},
        actual_arrival = CASE WHEN ${roadStatus} = 'At Port' THEN NOW() ELSE actual_arrival END,
        updated_at = NOW()
      WHERE road_transport_id = ${road.road_transport_id}
    `;
    if (roadStatus === 'Dispatched') {
      await prisma.shippingRecord.update({ where: { shipmentId: road.shipment_id }, data: { status: 'Dispatched' } });
    } else if (roadStatus === 'At Port') {
      await prisma.shippingRecord.update({ where: { shipmentId: road.shipment_id }, data: { status: 'At Port' } });
      await notifyRoles(['LOGISTICS', 'EXPORTER'], 'Truck Arrived at Port', `Container ${road.container_no} reached ${road.destination_port}.`, 'success');
    } else if (roadStatus === 'Loaded') {
      await prisma.shippingRecord.update({ where: { shipmentId: road.shipment_id }, data: { status: 'In Transit', shippedAt: new Date() } });
    }
    await prisma.auditLog.create({
      data: {
        action: 'DRIVER_GPS_CHECKPOINT_SUBMITTED',
        entityType: 'RoadTransport',
        entityId: road.road_transport_id,
        details: {
          shipmentId: road.shipment_id,
          checkpointName,
          eventType,
          roadStatus,
          latitude: numericLatitude,
          longitude: numericLongitude,
          locationAccuracyM: numericAccuracy,
          sealCondition,
          driverName: submittedDriverName,
          driverPhone: submittedDriverPhone,
          source: 'DRIVER_PHONE',
        },
        ipAddress: req.ip,
      }
    });
    await notifyRoles(['LOGISTICS'], 'Truck Company Checkpoint Received', `${submittedDriverName} submitted ${eventType} for container ${road.container_no}.`, 'info');
    res.status(201).json({ success: true, data: checkpointRows[0], status: roadStatus });
  } catch (error) {
    console.error('Error recording driver GPS checkpoint:', error);
    res.status(500).json({ message: 'Server error recording driver checkpoint.' });
  }
};

